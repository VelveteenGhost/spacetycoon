"""Turn export/manifest.json into src/ReplicatedStorage/Port/Manifest.luau.

Keeps what Studio code needs (studs, Roblox axes): each mesh's group, pivot, world box, size,
pivot offset, attachments and material maps. Placement notes stay in the JSON.

Usage: python3 tools/manifest_to_luau.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "export" / "manifest.json"
OUT = ROOT / "src" / "ReplicatedStorage" / "Port" / "Manifest.luau"


def num(x):
    s = f"{x:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def vec(v):
    return "{" + ", ".join(num(x) for x in v) + "}"


def main():
    meshes = json.loads(SRC.read_text())["meshes"]
    lines = [
        "--!strict",
        "-- Generated by tools/manifest_to_luau.py from export/manifest.json. Do not edit by hand.",
        "-- Studs, Roblox axes. Vectors are {x, y, z}; see Port.Manifest consumers for helpers.",
        "",
        "export type Attachment = { name: string, localStuds: { number }, worldStuds: { number } }",
        "export type Material = { name: string, maps: { [string]: string } }",
        "export type Mesh = {",
        "\tgroup: string,",
        "\tpivot: { number },",
        "\tbboxMin: { number },",
        "\tbboxMax: { number },",
        "\tsize: { number },",
        "\tpivotOffset: { number },",
        "\ttriangles: number,",
        "\tmaterials: { Material },",
        "\tattachments: { Attachment },",
        "}",
        "",
        "local meshes: { [string]: Mesh } = {",
    ]
    for name in sorted(meshes):
        m = meshes[name]
        lines.append(f"\t{name} = {{")
        lines.append(f"\t\tgroup = \"{m['group']}\",")
        lines.append(f"\t\tpivot = {vec(m['pivot_studs'])},")
        lines.append(f"\t\tbboxMin = {vec(m['bbox_min_studs'])},")
        lines.append(f"\t\tbboxMax = {vec(m['bbox_max_studs'])},")
        lines.append(f"\t\tsize = {vec(m['size_studs'])},")
        lines.append(f"\t\tpivotOffset = {vec(m['pivot_offset_studs'])},")
        lines.append(f"\t\ttriangles = {m['triangles']},")
        lines.append("\t\tmaterials = {")
        for mat in m["materials"]:
            maps = ", ".join(
                f"{k} = \"{Path(v).name}\"" for k, v in sorted(mat["maps"].items())
            )
            lines.append(f"\t\t\t{{ name = \"{mat['name']}\", maps = {{ {maps} }} }},")
        lines.append("\t\t},")
        lines.append("\t\tattachments = {")
        for a in m.get("attachments") or []:
            lines.append(
                f"\t\t\t{{ name = \"{a['name']}\", localStuds = {vec(a['local_studs'])}, "
                f"worldStuds = {vec(a['world_studs'])} }},"
            )
        lines.append("\t\t},")
        lines.append("\t},")
    lines += ["}", "", "return meshes", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"{OUT.relative_to(ROOT)}: {len(meshes)} meshes")


if __name__ == "__main__":
    main()
